<?php

namespace App\Policies;

use App\Models\FiscalDocument;
use App\Models\User;
use Illuminate\Auth\Access\Response;

class FiscalDocumentPolicy
{
    public function allFiscalDocument(?User $user): Response
    {
        if (!$user) return Response::denyWithStatus(401, 'Debes iniciar sesión.');

        if ($user->isEmployee()) {
            return $user->canAny(['FiscalDocument.All'])
                ? Response::allow()
                : Response::denyWithStatus(403, 'No cuenta con los permisos necesarios para ejecutar esta acción.');
        }

        return Response::denyWithStatus(403, 'No tienes permiso para listar tipos de entidades.');
    }

